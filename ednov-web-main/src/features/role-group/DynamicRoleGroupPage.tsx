import * as React from 'react';
import { useParams, Navigate } from 'react-router-dom';
import { DynamicRoleGroupManagementPage } from '@/components/common/DynamicRoleGroupManagementPage';
import { ProtectedRoute } from '@/components/layout/ProtectedRoute';

/**
 * Route-driven wrapper around DynamicRoleGroupManagementPage.
 *
 * URL: /dashboard/role-group/:groupCode
 *   - groupCode = role_group code with underscores replaced by hyphens
 *     (e.g. 'steering', 'operations', 'service-users')
 *
 * The page reads IE from the '{groupCode}' interface and builds its tabs dynamically.
 * A sidebar menu entry and tab IEs are auto-generated by the backend when a role is
 * created in that group (roles.service.ts::autoGenerateTabInterfaceElement).
 */
export const DynamicRoleGroupPage: React.FC = () => {
  const { groupCode } = useParams<{ groupCode: string }>();

  if (!groupCode) return <Navigate to="/dashboard" replace />;

  return (
    <ProtectedRoute requiredPermission={{ resource: groupCode, action: 'read' }}>
      <DynamicRoleGroupManagementPage
        interfaceName={groupCode}
        menuId={`menu-${groupCode}`}
        title={groupCode.charAt(0).toUpperCase() + groupCode.slice(1).replaceAll('-', ' ')}
        userQueryKey={groupCode}
      />
    </ProtectedRoute>
  );
};
